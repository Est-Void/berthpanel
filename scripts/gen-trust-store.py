#!/usr/bin/env python3
"""Convert the vendored CA bundle into a C++ translation unit.

Deterministic: same PEM in, same bytes out (the release build compares
artifacts byte-for-byte, dev.md §3). Reads third_party/trust/cacert.pem,
writes $(BUILD)/generated/trust_store.cpp defining berth::kTrustStorePem.
"""

import sys


def main() -> int:
    if len(sys.argv) != 3:
        print(f"usage: {sys.argv[0]} <cacert.pem> <out.cpp>", file=sys.stderr)
        return 2
    pem_path, out_path = sys.argv[1], sys.argv[2]

    with open(pem_path, "rb") as f:
        data = f.read()

    # mbedtls_x509_crt_parse detects PEM by buf[len-1] == '\0' and strstr's
    # the buffer, so the embedded array MUST be NUL-terminated (dev.md trap:
    # silence on a rejected input is a bug — this one would have failed
    # silently into the DER path).
    data_with_nul = data + b"\x00"

    lines = [
        "// Generated by scripts/gen-trust-store.py from third_party/trust/cacert.pem.",
        "// Do not edit. Regenerate with make. Pin: third_party/trust/VERSION.txt.",
        "#include <cstddef>",
        "",
        "namespace berth {",
        "",
        "// extern on the definition: without it a const array has internal",
        "// linkage and the symbol never leaves this translation unit.",
        "extern const unsigned char kTrustStorePem[] = {",
    ]
    for offset in range(0, len(data_with_nul), 16):
        chunk = data_with_nul[offset : offset + 16]
        hex_bytes = ", ".join(f"0x{b:02x}" for b in chunk)
        lines.append(f"    {hex_bytes},")
    lines += [
        "};",
        "",
        "extern const std::size_t kTrustStorePemLen = sizeof(kTrustStorePem);",
        "",
        "}  // namespace berth",
        "",
    ]

    with open(out_path, "w") as f:
        f.write("\n".join(lines))
    return 0


if __name__ == "__main__":
    sys.exit(main())
